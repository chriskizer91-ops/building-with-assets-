export const FONTS = {
  big: { glyphs: BIG, w: 5, h: 7, gap: 1 },
  small: { glyphs: SMALL, w: 3, h: 5, gap: 1 },
};

// Width in pixels of a string (bold adds one pixel per glyph).
export function measure(text, font = 'small', bold = false) {
  const f = FONTS[font];
  const n = [...String(text)].length;
  if (!n) return 0;
  return n * (f.w + (bold ? 1 : 0) + f.gap) - f.gap;
}

// Calls plot(x, y) for every lit pixel. italic slants the top rows right, like an old console logo.
export function glyphPixels(text, x, y, { font = 'small', bold = false, italic = false } = {}, plot) {
  const f = FONTS[font];
  let cx = x;
  for (const ch of String(text).toUpperCase()) {
    const rows = f.glyphs[ch] || f.glyphs['?'] || f.glyphs[' '];
    for (let r = 0; r < f.h; r++) {
      const shift = italic ? Math.floor((f.h - 1 - r) / 2) : 0;
      const row = rows[r];
      for (let c = 0; c < f.w; c++) {
        if (row[c] !== '#') continue;
        plot(cx + c + shift, y + r);
        if (bold) plot(cx + c + 1 + shift, y + r);
      }
    }
    cx += f.w + (bold ? 1 : 0) + f.gap;
  }
}

// Shortens a label until it fits in maxWidth pixels.
export function fit(text, maxWidth, font = 'small', bold = false) {
  let t = String(text).toUpperCase().replace(/[^A-Z0-9 .:!'&?/+-]/g, '');
  if (measure(t, font, bold) <= maxWidth) return t;
  while (t.length > 1 && measure(t + '..', font, bold) > maxWidth) t = t.slice(0, -1);
  return t.trimEnd() + '..';
}
